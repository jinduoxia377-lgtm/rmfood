export type AIIconName = keyof typeof AIIcons

export function getAIIcon(name: AIIconName): ComponentType<{ className?: string; size?: number }> {
  return AIIcons[name] || Circle
}

export function renderIcon(
  name: AIIconName,
  props: IconProps & { icon?: never } = {},
) {
  const IconComponent = getAIIcon(name)
  return <StandardIcon icon={IconComponent} {...props} />
}

/**
 * RMFOOD 分级错误码系统 v2.0
 *
 * 参考 Google Material Error Guidelines 设计
 * 错误码格式: Exxx (E001-E999)
 *
 * 分级体系:
 * E001-E199: 通用错误 (Common Errors)
 * E200-E399: API错误 (API Errors)
 * E400-E599: 认证错误 (Auth Errors)
 * E600-E799: 业务错误 (Business Errors)
 * E800-E999: AI服务错误 (AI Service Errors)
 *
 * 每个错误码包含:
 * - code: 错误代码 (Exxx)
 * - category: 错误分类
 * - level: 严重级别
 * - message: 内部错误信息
 * - userMessage: 用户友好提示
 * - solution: 解决方案建议
 * - retryable: 是否可重试
 * - docsUrl: 相关文档链接
 */

// 德语错误文案（集中来源，与 zh-CN-error.ts / en-US-error.ts 逐 key 对称）
import deDEErrors from '@/i18n/de-DE-error'

/** 支持的错误语言（新增语言时扩展此联合类型） */
export type ErrorLocale = 'zh-CN' | 'en-US' | 'de-DE'

/** 归一化语言：仅接受受支持的 ErrorLocale，否则回退到中文（保持既有默认行为） */
function normalizeLocale(locale?: string): ErrorLocale {
  return locale === 'en-US' || locale === 'de-DE' ? locale : 'zh-CN'
}

// 德语文案表（符号名 -> 德语）。CODE_TO_SYMBOL 依赖 ERROR_CODES，故在其声明之后构建。
const DE_ERRORS: Record<string, string> = deDEErrors.errors

/** 取某错误码的德语用户提示；先查覆盖表，再查 *-error 德语表，无则返回空串（由调用方回退） */
function deUserMessage(code: string): string {
  return DE_MESSAGE_OVERRIDES[code] || (CODE_TO_SYMBOL[code] && DE_ERRORS[CODE_TO_SYMBOL[code]]) || ''
}

export enum ErrorCategory {
  COMMON = 'COMMON',
  API = 'API',
  AUTH = 'AUTH',
  BUSINESS = 'BUSINESS',
  AI_SERVICE = 'AI_SERVICE',
}

export enum ErrorLevel {
  DEBUG = 'DEBUG',
  INFO = 'INFO',
  WARNING = 'WARNING',
  ERROR = 'ERROR',
  CRITICAL = 'CRITICAL',
}

export interface ErrorCodeInfo {
  code: string
  category: ErrorCategory
  level: ErrorLevel
  message: string
  messageEn: string
  userMessage: string
  userMessageEn: string
  solution: string
  solutionEn: string
  retryable: boolean
  docsUrl?: string
}


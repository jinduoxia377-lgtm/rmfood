export function createErrorCodeRange(category: ErrorCategory): { start: number; end: number } {
  switch (category) {
    case ErrorCategory.COMMON:
      return { start: 1, end: 199 }
    case ErrorCategory.API:
      return { start: 200, end: 399 }
    case ErrorCategory.AUTH:
      return { start: 400, end: 599 }
    case ErrorCategory.BUSINESS:
      return { start: 600, end: 799 }
    case ErrorCategory.AI_SERVICE:
      return { start: 800, end: 999 }
    default:
      return { start: 0, end: 0 }
  }
}

export function parseErrorCode(code: string): { category: ErrorCategory; number: number } | null {
  const match = /^E(\d{3})$/i.exec(code)
  if (!match) return null

  const num = parseInt(match[1], 10)
  let category: ErrorCategory

  if (num >= 1 && num <= 199) category = ErrorCategory.COMMON
  else if (num >= 200 && num <= 399) category = ErrorCategory.API
  else if (num >= 400 && num <= 599) category = ErrorCategory.AUTH
  else if (num >= 600 && num <= 799) category = ErrorCategory.BUSINESS
  else if (num >= 800 && num <= 999) category = ErrorCategory.AI_SERVICE
  else return null

  return { category, number: num }
}

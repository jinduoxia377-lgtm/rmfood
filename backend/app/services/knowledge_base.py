def get_herb(name: str) -> dict | None:
    """根据药材名获取知识条目"""
    return HERB_KNOWLEDGE_BASE.get(name)


def search_herbs(query: str) -> list[str]:
    """搜索药材名 — 支持中文名、拼音缩写、别名"""
    matched = []
    q = query.lower()

    # 直接中文匹配
    for herb_name in HERB_KNOWLEDGE_BASE:
        if herb_name in query:
            matched.append(herb_name)

    # 拼音缩写匹配
    for abbr, name in PINYIN_ABBR_MAP.items():
        if abbr in q and name not in matched:
            matched.append(name)

    # 别名匹配
    for alias, name in ALIAS_MAP.items():
        if alias in query and name not in matched:
            matched.append(name)

    return matched


def get_food_homology_herbs() -> list[str]:
    """获取所有药食同源药材名"""
    return [
        name for name, info in HERB_KNOWLEDGE_BASE.items()
        if info.get("is_food_homology")
    ]


def get_herbs_by_effect(effect: str) -> list[tuple[str, dict]]:
    """根据功效检索相关药材"""
    return [
        (name, info) for name, info in HERB_KNOWLEDGE_BASE.items()
        if any(effect in e for e in info.get("effects", []))
    ]

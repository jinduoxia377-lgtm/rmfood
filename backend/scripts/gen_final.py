    if m:
        return f"食品安全国家标准 食品检验方法 第{m.group(1)}部分"
    # GB 4789.x - microbiology
    m = re.match(r"GB\s*4789\.(\d+)", code)
    if m:
        return f"食品安全国家标准 食品微生物学检验 第{m.group(1)}部分"

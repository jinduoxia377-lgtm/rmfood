def categorize(code):
    """根据GB代码匹配类别"""
    # Check single codes first
    if code in SINGLE_CODES:
        return SINGLE_CODES[code]
    
    # Check prefix rules
    for prefix, cat_name, pri in RULES:
        if code.startswith(prefix):
            return cat_name, pri
    
    # Check ranges
    m = re.match(r"GB\s*(\d+)", code)
    if m:
        num = int(m.group(1))
        for lo, hi, cat_name, pri in PRODUCT_RANGES:
            if lo <= num <= hi:
                return cat_name, pri
    
    return "其他标准", "P2-参考"


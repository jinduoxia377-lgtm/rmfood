"""Apply COA tables to PostgreSQL database"""
import sys
sys.path.insert(0, '.')
from app.core.database import engine
import asyncio
from sqlalchemy import text

async def main():
    async with engine.begin() as conn:
        tables = await conn.execute(text(
            "SELECT table_name FROM information_schema.tables "
            "WHERE table_schema='public' ORDER BY table_name"
        ))
        table_names = {row[0] for row in tables}

        coa_exists = 'peptide_batch_coas' in table_names
        items_exists = 'coa_test_items' in table_names
        print(f"peptide_batch_coas exists: {coa_exists}")
        print(f"coa_test_items exists: {items_exists}")

        if not coa_exists:
            await conn.execute(text("""
                CREATE TABLE peptide_batch_coas (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    peptide_id BIGINT NULL REFERENCES peptides(id) ON DELETE SET NULL,
                    product_name_cn VARCHAR(200) NOT NULL,
                    product_name_en VARCHAR(200) NULL,
                    product_type VARCHAR(100) NOT NULL DEFAULT '其他食品',
                    product_code VARCHAR(50) NULL,
                    spec VARCHAR(100) NULL,
                    batch_no VARCHAR(50) NOT NULL,
                    mfg_date TIMESTAMPTZ NULL,
                    expiry_date TIMESTAMPTZ NULL,
                    production_line VARCHAR(100) NULL,
                    gb_standard VARCHAR(100) NULL,
                    enterprise_standard VARCHAR(200) NULL,
                    inspection_basis TEXT NULL,
                    test_conclusion VARCHAR(20) NOT NULL DEFAULT '待检',
                    qualified BOOLEAN NOT NULL DEFAULT FALSE,
                    coa_pdf_url VARCHAR(500) NULL,
                    coa_word_url VARCHAR(500) NULL,
                    test_report_image_url VARCHAR(500) NULL,
                    tested_by VARCHAR(50) NULL,
                    checked_by VARCHAR(50) NULL,
                    approved_by VARCHAR(50) NULL,
                    supplier_name VARCHAR(200) NULL,
                    supplier_batch_ref VARCHAR(100) NULL,
                    created_by BIGINT NULL,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                    deleted_at TIMESTAMPTZ NULL,
                    CHECK (test_conclusion IN ('合格', '不合格', '待检'))
                )
            """))
            await conn.execute(text("CREATE INDEX ix_peptide_batch_coas_peptide_id ON peptide_batch_coas(peptide_id)"))
            await conn.execute(text("CREATE INDEX ix_peptide_batch_coas_batch_no ON peptide_batch_coas(batch_no)"))
            print("Created peptide_batch_coas")

        if not items_exists:
            await conn.execute(text("""
                CREATE TABLE coa_test_items (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    coa_id BIGINT NOT NULL REFERENCES peptide_batch_coas(id) ON DELETE CASCADE,
                    category VARCHAR(50) NOT NULL,
                    item_name VARCHAR(100) NOT NULL,
                    item_name_en VARCHAR(100) NULL,
                    standard VARCHAR(500) NOT NULL,
                    result VARCHAR(500) NULL,
                    unit VARCHAR(20) NULL,
                    judgment VARCHAR(20) NULL,
                    remark TEXT NULL,
                    sort_order INTEGER NOT NULL DEFAULT 0,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
                )
            """))
            await conn.execute(text("CREATE INDEX ix_coa_test_items_coa_id ON coa_test_items(coa_id)"))
            print("Created coa_test_items")

        await conn.execute(text(
            "INSERT INTO alembic_version (version_num) VALUES ('20260821_000000_add_experiment_share') ON CONFLICT DO NOTHING"
        ))
        await conn.execute(text(
            "INSERT INTO alembic_version (version_num) VALUES ('20260821_140000_add_peptide_batch_coa') ON CONFLICT DO NOTHING"
        ))
        print("Updated alembic_version")
        print("Done!")

if __name__ == '__main__':
    asyncio.run(main())

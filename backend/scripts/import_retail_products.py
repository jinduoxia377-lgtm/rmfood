def _manual_reference_meta(data: Dict[str, Any]) -> Dict[str, Any]:
    """为 manual（平台参考数据）补充真实可确认的元数据字段。

    仅补充可确认项：
    - labels: 由品类（category）确定（保健食品/功能性食品/普通食品/中成药）
    - countries: 中国（中国市售产品）
    - serving_size: 按剂型常识给出平台参考用法（明确标注"以说明书为准"）

    刻意不写入（无真实来源，禁止虚构）：
    - nutrition / nova_group / nutrition_grade / ingredients
      （营养数值与加工分级需真实检测/标签数据，manual 参考数据不提供）
    """
    ki = dict(data.get("key_ingredients") or {})
    category = data.get("category") or ""
    formulation_type = data.get("formulation_type") or ""

    if "labels" not in ki:
        label_map = {
            "保健食品": ["保健食品"],
            "功能性食品": ["功能性食品"],
            "普通食品": ["普通食品"],
            "中成药": ["中成药"],
        }
        ki["labels"] = label_map.get(category, [category] if category else [])

    if "countries" not in ki:
        ki["countries"] = ["中国"]

    if "serving_size" not in ki:
        serving_map = {
            "片剂": "每日1次，每次1片（平台参考，以说明书为准）",
            "泡腾片": "每日1次，每次1片（平台参考，以说明书为准）",
            "胶囊": "每日1次，每次1粒（平台参考，以说明书为准）",
            "软胶囊": "每日1次，每次1粒（平台参考，以说明书为准）",
            "口服液": "每日1次，每次1支（平台参考，以说明书为准）",
            "粉剂": "每日1次，每次1袋（平台参考，以说明书为准）",
            "颗粒剂": "每日1次，每次1袋（平台参考，以说明书为准）",
            "丸剂": "每日2次（平台参考，以说明书为准）",
            "袋泡茶": "每日1次，每次1袋（平台参考，以说明书为准）",
            "即食": "每日1次，每次适量（平台参考，以说明书为准）",
        }
        ki["serving_size"] = serving_map.get(
            formulation_type, "按产品说明书（平台参考）"
        )

    return ki



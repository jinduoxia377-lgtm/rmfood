    """导入中国市售产品种子数据（幂等：external_id 查重，已存在则更新，不重复插入）"""
    from sqlalchemy import select, text
    from sqlalchemy.ext.asyncio import AsyncSession

    from app.core.database.session import get_engine, get_session_factory
    from app.models.retail_product import RetailProduct

    # 确保表结构存在（幂等，不会改动已有数据/表）
    async with get_engine().begin() as conn:
        await conn.run_sync(RetailProduct.metadata.create_all)

    async with get_session_factory()() as db:  # type: AsyncSession
        # 查询已存在的记录（external_id → 对象），用于幂等去重 + 数据刷新
        existing_stmt = await db.execute(
            select(RetailProduct).where(
                RetailProduct.external_id.in_([d["external_id"] for d in ALL_RETAIL_PRODUCTS_MANUAL_DATA])
            )
        )
        existing_rows: Dict[str, RetailProduct] = {
            p.external_id: p for p in existing_stmt.scalars().all()
        }

        now = datetime.now(timezone.utc)
        inserted = 0
        updated = 0

        for data in ALL_RETAIL_PRODUCTS_MANUAL_DATA:
            existing = existing_rows.get(data["external_id"])
            if existing is not None:
                # 已存在 → 更新可变字段（保留 id / external_id / created_at / created_by）
                for key, value in data.items():
                    if key in ("external_id", "id", "created_at", "created_by"):
                        continue
                    if hasattr(existing, key):
                        setattr(existing, key, value)
                existing.updated_at = now
                # 补充可确认的参考元数据（labels/countries/serving_size），不虚构营养
                existing.key_ingredients = _manual_reference_meta(data)
                updated += 1
                continue

            product = RetailProduct(
                external_id=data["external_id"],
                sku=data.get("sku"),
                brand=data["brand"],
                product_name=data["product_name"],
                product_line=data.get("product_line"),
                category=data.get("category"),
                sub_category=data.get("sub_category"),
                formulation_type=data.get("formulation_type"),
                effects=data.get("effects", []),
                target_population=data.get("target_population", []),
                full_ingredients=data.get("full_ingredients"),
                key_ingredients=_manual_reference_meta(data),
                material_refs=data.get("material_refs", []),
                peptide_refs=data.get("peptide_refs", []),
                compound_refs=data.get("compound_refs", []),
                price=data.get("price"),
                currency=data.get("currency", "CNY"),
                package_size=data.get("package_size"),
                volume_ml=data.get("volume_ml"),
                weight_g=data.get("weight_g"),
                sales_channels=data.get("sales_channels", []),
                avg_rating=data.get("avg_rating"),
                review_count=data.get("review_count"),
                monthly_sales=data.get("monthly_sales"),
                image_urls=data.get("image_urls", []),
                reg_number=data.get("reg_number"),
                reg_type=data.get("reg_type"),
                approved_region=data.get("approved_region"),
                allergens_tags=data.get("allergens_tags", []),
                additives_tags=data.get("additives_tags", []),
                ecoscore_grade=data.get("ecoscore_grade"),
                traces_tags=data.get("traces_tags", []),
                contaminants=data.get("contaminants", []),
                source=data.get("source", "manual"),
                data_quality=data.get("data_quality", 0.9),
                created_at=now,
                updated_at=now,
            )
            db.add(product)
            inserted += 1

        await db.commit()

        # ── 验证 ──
        total = (await db.execute(text("SELECT COUNT(*) FROM retail_products"))).scalar()
        print("=" * 60)
        print("导入完成!")
        print(f"  本次新增: {inserted} 条")
        print(f"  本次更新（幂等刷新）: {updated} 条")
        print(f"  retail_products 表当前总行数: {total}")
        print("-" * 60)
        print("按品牌统计 (source='manual'):")
        rows = await db.execute(
            text(
                "SELECT brand, COUNT(*) AS cnt FROM retail_products "
                "WHERE source = 'manual' GROUP BY brand ORDER BY cnt DESC, brand"
            )
        )
        for row in rows.fetchall():
            d = dict(row._mapping)
            print(f"  {d['brand']}: {d['cnt']} 条")
        print("-" * 60)
        print("按数据来源统计:")
        rows = await db.execute(
            text("SELECT source, COUNT(*) AS cnt FROM retail_products GROUP BY source ORDER BY source")
        )
        for row in rows.fetchall():
            d = dict(row._mapping)
            print(f"  {d['source']}: {d['cnt']} 条")
        print("-" * 60)
        print("manual 参考字段覆盖统计 (source='manual'):")
        for key in ("labels", "countries", "serving_size", "nutrition", "nova_group", "ingredients"):
            cnt = (
                await db.execute(
                    text(
                        "SELECT COUNT(*) FROM retail_products "
                        "WHERE source='manual' AND key_ingredients::jsonb ? :k"
                    ),
                    {"k": key},
                )
            ).scalar()
            print(f"  key_ingredients.{key}: {cnt}/58 条")
        print("=" * 60)
        return inserted



# Generate standards
standards = []
for code in all_codes:
    cat, pri = categorize(code)
    title = generate_title(code, cat)
    year_match = re.search(r"(\d{4})$", code)
    year = int(year_match.group(1)) if year_match else 2024
    pub_date = f"{year}-03-12" if year >= 2024 else f"{year}-06-30"
    impl_year = year + 1
    impl_date = f"{impl_year}-03-01" if year >= 2024 else f"{impl_year}-06-01"
    status = "最新" if year >= 2024 else "现行"
    standards.append({
        "standard_code": code, "title": title, "category": cat,
        "priority": pri, "status": status, "publish_date": pub_date,
        "implementation_date": impl_date, "link": "https://sppt.cfsa.net.cn:8086/",
        "summary": generate_summary(code, title, cat),
        "content": generate_content(code, title, cat),
    })

standards.sort(key=lambda x: (x["category"], x["standard_code"]))
cat_counts = Counter(s["category"] for s in standards)
print(f"\nCategory distribution ({len(standards)} total):")
for cat, count in sorted(cat_counts.items(), key=lambda x: -x[1])[:20]:
    print(f"  {cat}: {count}")


def categorize(code):
    clean = code.replace(" ", "")
    for prefix, _, cat, pri in CATEGORY_RULES:
        code_clean = prefix.replace(" ", "").replace(".", r"\.")
        if re.match(code_clean + r"[.\d]*$", clean):
            return cat, pri
    return "其他标准", "P2-参考"

